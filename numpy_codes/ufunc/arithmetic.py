import numpy as np

array1 = np.array([5,10,15,20,25])
array2 = np.array([2,4,6,8,10])

add = np.add(array1,array2)

print(add)

sub = np.subtract(array1,array2)

print(sub)

mul = np.multiply(array1,array2)

print(mul)

divide = np.divide(array1,array2)

print(divide)

power = np.power(array1, array2)

print(power)